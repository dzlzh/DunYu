"""Rebuild committed runtime assets; --check compares without writing files.

Install scripts/asset-requirements.txt first. Original artwork/fonts stay intact.
"""
import argparse
import io
import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'resources/optimized'
CHECK = argparse.ArgumentParser()
CHECK.add_argument('--check', action='store_true')
CHECK = CHECK.parse_args().check

# Original source rectangles, including regions used by stroke() and ring().
ATLASES = {
    'main': ('docs/design/ui-settings.png', {
        'MAIN_SURFACE': (400, 285, 500, 90), 'MAIN_PAPER': (40, 720, 400, 180),
        'STROKE_RED': (1345, 131, 151, 13), 'STROKE_INK': (42, 232, 153, 14)}),
    'full': ('docs/design/rest-preview-fullscreen-static.png', {
        'FULL_TOP': (1332, 0, 250, 220), 'FULL_PAPER': (20, 240, 400, 400),
        'FULL_RIGHT': (1582, 90, 90, 130), 'RING': (661, 261, 350, 350),
        'FULL_BOTTOM': (0, 741, 340, 200)}),
    'card': ('docs/design/rest-preview-card.png', {'CARD_PAPER': (80, 190, 300, 250)}),
    'nav': ('resources/nav-icons-ink.png', {
        f'NAV_{i}': r for i, r in enumerate([
            (230, 150, 250, 200), (630, 180, 290, 170), (1040, 180, 310, 170),
            (230, 470, 250, 230), (630, 510, 290, 190), (1060, 480, 280, 230)])}),
}


def emit(name, data):
    path = OUT / name
    if CHECK:
        actual = path.read_bytes() if path.exists() else None
        if actual is not None and path.suffix == '.rs':
            actual = actual.replace(b'\r\n', b'\n')
        # Pillow wheels may use different zlib builds across platforms. Compare
        # decoded pixels, not compression bytes; text tolerates Git CRLF checkout.
        if actual is not None and path.suffix == '.png':
            with Image.open(io.BytesIO(actual)) as existing, Image.open(io.BytesIO(data)) as expected:
                if existing.size == expected.size and existing.convert('RGBA').tobytes() == expected.convert('RGBA').tobytes():
                    actual = data
        if actual != data:
            raise SystemExit(f'Stale asset: {path.relative_to(ROOT)}; run scripts/prepare-assets.py')
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f'{name}: {len(data):,} bytes')


constants = ['// Generated by scripts/prepare-assets.py; do not edit.']
for name, (source, regions) in ATLASES.items():
    with Image.open(ROOT / source) as image:
        image = image.convert('RGBA')
        # Keep four pixels of original neighbours for bicubic sampling. At an
        # original image edge leave the region at the atlas edge too, preserving
        # GDI+ edge sampling rather than introducing synthetic border colours.
        crops = []
        for symbol, (x, y, w, h) in regions.items():
            box = (max(0, x-4), max(0, y-4), min(image.width, x+w+4), min(image.height, y+h+4))
            crops.append((symbol, (x, y, w, h), box, image.crop(box)))
        width = max(crop.width for _, _, _, crop in crops)
        height = sum(crop.height for _, _, _, crop in crops)
        atlas = Image.new('RGBA', (width, height))
        top = 0
        for symbol, (x, y, w, h), box, crop in crops:
            left = width-crop.width if x+w == image.width else 0
            atlas.paste(crop, (left, top))
            rect = (left+x-box[0], top+y-box[1], w, h)
            actual = atlas.crop((rect[0], rect[1], rect[0]+w, rect[1]+h))
            assert actual.tobytes() == image.crop((x, y, x+w, y+h)).tobytes()
            constants.append(f'pub const {symbol}: [f32; 4] = [{", ".join(str(v)+"." for v in rect)}];')
            top += crop.height
        buffer = io.BytesIO()
        atlas.save(buffer, format='PNG', optimize=True)
        emit(f'{name}.png', buffer.getvalue())
emit('regions.rs', ('\n'.join(constants)+'\n').encode())

chars = set(range(32, 127))
for lead in range(0xa1, 0xf8):
    for trail in range(0xa1, 0xff):
        try:
            chars.add(ord(bytes([lead, trail]).decode('gb2312')))
        except UnicodeDecodeError:
            pass
source_chars = set()
for source in sorted((ROOT / 'src').rglob('*.rs')):
    text = source.read_text(encoding='utf-8')
    source_chars.update(ord(c) for c in text if c.isprintable())
    source_chars.update(int(value.replace('_', ''), 16) for value in re.findall(r'\\u\{([0-9a-fA-F_]+)\}', text))
chars.update(source_chars)

coverage = None
for weight in ['Regular', 'SemiBold']:
    font = TTFont(ROOT / f'resources/fonts/SourceHanSerifSC-{weight}.otf', recalcTimestamp=False)
    missing = source_chars - set(font.getBestCmap()) - {0x25b4, 0x25b8, 0x25be}
    if missing:
        raise SystemExit(f'UI characters unsupported by original font: {sorted(missing)}')
    wanted = chars & set(font.getBestCmap())
    # Some UI icons are vector drawn and have no glyph even in the original font.
    coverage = wanted if coverage is None else coverage & wanted
    metrics = {t: {k: getattr(font[t], k) for k in fields} for t, fields in {
        'hhea': ['ascent', 'descent', 'lineGap'],
        'OS/2': ['sTypoAscender', 'sTypoDescender', 'sTypoLineGap', 'usWinAscent', 'usWinDescent'],
    }.items()}
    widths = {cp: font['hmtx'][glyph] for cp, glyph in font.getBestCmap().items() if cp in wanted}
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    options.layout_features = ['*']
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=wanted)
    sub.subset(font)
    # Rename identity records, retaining the original copyright/licence notices.
    for record in font['name'].names:
        if record.nameID in {1, 3, 4, 6, 16, 18, 20, 21, 25}:
            value = record.toUnicode().replace('Source Han Serif', 'DunYu Serif').replace('SourceHanSerif', 'DunYuSerif').replace('思源宋体', '遁鱼宋体')
            record.string = value.encode(record.getEncoding())
    cff = font['CFF '].cff
    cff.fontNames = [n.replace('SourceHanSerif', 'DunYuSerif') for n in cff.fontNames]
    for top in cff.topDictIndex:
        for key in ['FamilyName', 'FullName', 'FontName']:
            if hasattr(top, key):
                setattr(top, key, getattr(top, key).replace('Source Han Serif', 'DunYu Serif').replace('SourceHanSerif', 'DunYuSerif'))
    buffer = io.BytesIO()
    font.save(buffer)
    data = buffer.getvalue()
    rebuilt = TTFont(io.BytesIO(data))
    assert wanted <= set(rebuilt.getBestCmap())
    assert all(rebuilt['hmtx'][rebuilt.getBestCmap()[cp]] == width for cp, width in widths.items())
    assert all(getattr(rebuilt[t], k) == v for t, fields in metrics.items() for k, v in fields.items())
    emit(f'DunYuSerifSC-{weight}.otf', data)

ranges = []
for cp in sorted(coverage):
    if ranges and cp == ranges[-1][1]+1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])
emit('coverage.rs', ('// Generated by scripts/prepare-assets.py; do not edit.\n'
    'pub const COVERAGE: &[(u32, u32)] = &[\n' + ''.join(f'    ({a}, {b}),\n' for a, b in ranges) + '];\n').encode())
print(f'Both fonts cover {len(coverage)} requested code points.')
